-- =====================================================================
-- Bloco de Join 1: análises comerciais
-- =====================================================================
DECLARE
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('         BLOCO JOIN 1 - ANÁLISES COMERCIAIS          ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');

    -- Query 1: assinaturas por plano
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Query 1: assinaturas por plano ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Plano',14)||RPAD('Qtd',6)||RPAD('Receita',16)||'Ticket Médio');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',55,'-'));
    FOR r IN (
        SELECT p.NAME AS plan,
               COUNT(s.ID) AS qty,
               SUM(s.CONTRACTED_VALUE) AS revenue,
               ROUND(AVG(s.CONTRACTED_VALUE),2) AS ticket
        FROM TB_CAD_SUBSCRIPTION s
        JOIN TB_CAD_PLAN p ON p.ID = s.PLAN_ID
        GROUP BY p.NAME
        ORDER BY revenue DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.plan,14)||RPAD(r.qty,6)||
            RPAD('R$ '||TO_CHAR(r.revenue,'FM99990.00'),16)||
            'R$ '||TO_CHAR(r.ticket,'FM99990.00'));
    END LOOP;

    -- Query 2: assinaturas por método de pagamento
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Query 2: assinaturas por método de pagamento ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Método',20)||RPAD('Qtd',6)||'Total');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',45,'-'));
    FOR r IN (
        SELECT pm.NAME AS method,
               COUNT(s.ID) AS qty,
               SUM(s.CONTRACTED_VALUE) AS total
        FROM TB_CAD_SUBSCRIPTION s
        JOIN TB_CAD_PAYMENT_METHOD pm ON pm.ID = s.PAYMENT_METHOD_ID
        GROUP BY pm.NAME
        ORDER BY qty DESC, total DESC
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.method,20)||RPAD(r.qty,6)||
            'R$ '||TO_CHAR(r.total,'FM99990.00'));
    END LOOP;

    -- Query 3: pets por espécie e status
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Query 3: pets por espécie e status ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Espécie',12)||RPAD('Status',16)||'Qtd');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',40,'-'));
    FOR r IN (
        SELECT e.NAME AS species,
               st.NAME AS status,
               COUNT(p.ID) AS qty
        FROM TB_CAD_PET p
        JOIN TB_CAD_SPECIES e ON e.ID = p.SPECIES_ID
        JOIN TB_CAD_SUBSCRIPTION s ON s.PET_ID = p.ID
        JOIN TB_CAD_SUB_STATUS st ON st.ID = s.STATUS_ID
        GROUP BY e.NAME, st.NAME
        ORDER BY e.NAME, st.NAME
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.species,12)||RPAD(r.status,16)||r.qty);
    END LOOP;
END;
/

