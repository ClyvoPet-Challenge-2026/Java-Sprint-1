        JOIN TB_CAD_CITY c ON c.ID = o.CITY_ID
        JOIN TB_CAD_PET p ON p.OWNER_ID = o.ID
        GROUP BY o.NAME, c.NAME
        HAVING COUNT(p.ID) > 1
        ORDER BY pet_count DESC, o.NAME
    ) LOOP
