-- =====================================================================
-- Cursor explícito 2: lembretes com classificação de alerta
-- =====================================================================
DECLARE
    CURSOR c_reminders IS
        SELECT l.TITLE, l.DUE_DATE, l.STATUS,
               p.NAME AS pet, o.NAME AS owner
        FROM TB_HEA_REMINDER l
        JOIN TB_CAD_PET p ON p.ID = l.PET_ID
        JOIN TB_CAD_OWNER o ON o.ID = p.OWNER_ID
        ORDER BY l.STATUS, l.DUE_DATE;

    v_alert      VARCHAR2(20);
    v_pending    NUMBER := 0;
    v_completed  NUMBER := 0;
    v_overdue    NUMBER := 0;
    v_upcoming   NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('   CURSOR 2 - LEMBRETES COM CLASSIFICAÇÃO DE ALERTA  ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE(RPAD('Título',28)||RPAD('Pet',12)||RPAD('Data',14)||
        RPAD('Status',12)||'Alerta');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',80,'-'));

    FOR reg IN c_reminders LOOP
        -- Tomada de decisão: definir alerta com base no status e data
        IF reg.STATUS = 'PENDING' THEN
            v_pending := v_pending + 1;
            IF reg.DUE_DATE < SYSDATE THEN
                v_alert   := 'ATRASADO';
                v_overdue := v_overdue + 1;
            ELSIF reg.DUE_DATE <= SYSDATE + 30 THEN
                v_alert    := 'PRÓXIMO';
                v_upcoming := v_upcoming + 1;
            ELSE
                v_alert := 'OK';
            END IF;
        ELSE
            v_completed := v_completed + 1;
            v_alert     := '-';
        END IF;

        DBMS_OUTPUT.PUT_LINE(RPAD(reg.TITLE,28)||RPAD(reg.pet,12)||
            RPAD(TO_CHAR(reg.DUE_DATE,'DD/MM/YYYY'),14)||
            RPAD(reg.STATUS,12)||v_alert);
    END LOOP;

    -- Resumo
    DBMS_OUTPUT.PUT_LINE(RPAD('-',80,'-'));
    DBMS_OUTPUT.PUT_LINE('Pendentes:  '||v_pending||'   Concluídos: '||v_completed);
    DBMS_OUTPUT.PUT_LINE('Atrasados:  '||v_overdue||'   Próximos (30d): '||v_upcoming);
END;
