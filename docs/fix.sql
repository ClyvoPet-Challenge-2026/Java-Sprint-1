-- =====================================================================
-- Cursor explícito 1: pets ativos com categorização de valor
-- =====================================================================
DECLARE
    CURSOR c_active_pets IS
        SELECT p.NAME AS pet, e.NAME AS species, o.NAME AS owner,
               pl.NAME AS plan, s.CONTRACTED_VALUE
        FROM TB_CAD_PET p
        JOIN TB_CAD_SPECIES e ON e.ID = p.SPECIES_ID
        JOIN TB_CAD_OWNER o ON o.ID = p.OWNER_ID
        JOIN TB_CAD_SUBSCRIPTION s ON s.PET_ID = p.ID
        JOIN TB_CAD_PLAN pl ON pl.ID = s.PLAN_ID
        JOIN TB_CAD_SUB_STATUS st ON st.ID = s.STATUS_ID
        WHERE st.NAME = 'ACTIVE'
        ORDER BY s.CONTRACTED_VALUE DESC;

    v_category   VARCHAR2(20);
    v_total      NUMBER := 0;
    v_count      NUMBER := 0;
    v_count_prem NUMBER := 0;
    v_count_int  NUMBER := 0;
    v_count_bas  NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('   CURSOR 1 - PETS ATIVOS COM CATEGORIZAÇÃO          ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE(RPAD('Pet',12)||RPAD('Espécie',12)||RPAD('Tutor',20)||
        RPAD('Plano',12)||RPAD('Valor',12)||'Categoria');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',80,'-'));

    FOR reg IN c_active_pets LOOP
        -- Tomada de decisão: faixa de valor
        IF reg.CONTRACTED_VALUE >= 150 THEN
            v_category   := 'Premium+';
            v_count_prem := v_count_prem + 1;
        ELSIF reg.CONTRACTED_VALUE >= 80 THEN
            v_category  := 'Intermediário';
            v_count_int := v_count_int + 1;
        ELSE
            v_category  := 'Básico';
            v_count_bas := v_count_bas + 1;
        END IF;

        DBMS_OUTPUT.PUT_LINE(RPAD(reg.pet,12)||RPAD(reg.species,12)||
            RPAD(reg.owner,20)||RPAD(reg.plan,12)||
            RPAD('R$ '||TO_CHAR(reg.CONTRACTED_VALUE,'FM990.00'),12)||v_category);

        v_total := v_total + reg.CONTRACTED_VALUE;
        v_count := v_count + 1;
    END LOOP;

    -- Resumo
    DBMS_OUTPUT.PUT_LINE(RPAD('-',80,'-'));
    DBMS_OUTPUT.PUT_LINE('Total de pets ativos: '||v_count);
    DBMS_OUTPUT.PUT_LINE('  Premium+:     '||v_count_prem);
    DBMS_OUTPUT.PUT_LINE('  Intermediário: '||v_count_int);
    DBMS_OUTPUT.PUT_LINE('  Básico:        '||v_count_bas);
    DBMS_OUTPUT.PUT_LINE('Receita total ativa: R$ '||TO_CHAR(v_total,'FM99990.00'));
END;
