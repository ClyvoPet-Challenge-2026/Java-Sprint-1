-- =====================================================================
-- Cursor explícito 3: histórico de eventos por pet (quebra de grupo)
-- =====================================================================
DECLARE
    CURSOR c_events IS
        SELECT p.NAME AS pet, e.NAME AS species, cl.NAME AS clinic,
               ec.EVENT_TYPE, ec.STATUS AS event_status, ec.EVENT_DATE
        FROM TB_HEA_CLINICAL_EVENT ec
        JOIN TB_CAD_PET p ON p.ID = ec.PET_ID
        JOIN TB_CAD_SPECIES e ON e.ID = p.SPECIES_ID
        JOIN TB_CAD_CLINIC cl ON cl.ID = ec.CLINIC_ID
        ORDER BY p.NAME, ec.EVENT_DATE;

    v_current_pet VARCHAR2(100) := NULL;
    v_pet_total   NUMBER := 0;
    v_grand_total NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('   CURSOR 3 - HISTÓRICO DE EVENTOS POR PET           ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');

    FOR reg IN c_events LOOP
        -- Tomada de decisão: detectar mudança de pet para imprimir cabeçalho
        IF v_current_pet IS NULL OR reg.pet <> v_current_pet THEN
            IF v_current_pet IS NOT NULL THEN
                DBMS_OUTPUT.PUT_LINE('  Subtotal '||v_current_pet||': '||v_pet_total||' evento(s)');
                DBMS_OUTPUT.PUT_LINE('');
            END IF;
            v_current_pet := reg.pet;
            v_pet_total   := 0;
            DBMS_OUTPUT.PUT_LINE('--- '||reg.pet||' ('||reg.species||') ---');
        END IF;

        DBMS_OUTPUT.PUT_LINE('  '||RPAD(TO_CHAR(reg.EVENT_DATE,'DD/MM/YYYY'),14)||
            RPAD(reg.event_type,14)||RPAD(reg.clinic,22)||reg.event_status);

        v_pet_total   := v_pet_total + 1;
        v_grand_total := v_grand_total + 1;
    END LOOP;

    -- Imprimir subtotal do último grupo
    IF v_current_pet IS NOT NULL THEN
        DBMS_OUTPUT.PUT_LINE('  Subtotal '||v_current_pet||': '||v_pet_total||' evento(s)');
    END IF;

    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('Total geral: '||v_grand_total||' eventos');
END;
