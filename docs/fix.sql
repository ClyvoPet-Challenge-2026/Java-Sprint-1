        JOIN TB_CAD_PET p ON p.OWNER_ID = o.ID
        JOIN TB_HEA_REMINDER l ON l.PET_ID = p.ID
        WHERE l.STATUS = 'PENDING'
        GROUP BY o.NAME
        ORDER BY next_due
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(RPAD(r.owner,22)||RPAD(r.qty,6)||
            TO_CHAR(r.next_due,'DD/MM/YYYY'));
    END LOOP;
END;
