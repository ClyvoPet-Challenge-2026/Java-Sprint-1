-- =====================================================================
-- Cursor explícito 4: receita por estado com ranqueamento
-- =====================================================================
DECLARE
    CURSOR c_state_revenue IS
        SELECT st.NAME AS state, st.UF,
               COUNT(s.ID) AS qty,
               SUM(s.CONTRACTED_VALUE) AS revenue
        FROM TB_CAD_SUBSCRIPTION s
        JOIN TB_CAD_PET p ON p.ID = s.PET_ID
        JOIN TB_CAD_OWNER o ON o.ID = p.OWNER_ID
        JOIN TB_CAD_CITY c ON c.ID = o.CITY_ID
        JOIN TB_CAD_STATE st ON st.ID = c.STATE_ID
        GROUP BY st.NAME, st.UF
        ORDER BY revenue DESC;

    v_rank        NUMBER := 0;
    v_total       NUMBER := 0;
    v_performance VARCHAR2(10);
    v_high        NUMBER := 0;
    v_mid         NUMBER := 0;
    v_low         NUMBER := 0;
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('   CURSOR 4 - RECEITA POR ESTADO COM RANQUEAMENTO    ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE(RPAD('Rank',6)||RPAD('UF',5)||RPAD('Estado',22)||
        RPAD('Contratos',12)||RPAD('Receita',16)||'Desempenho');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',80,'-'));

    FOR reg IN c_state_revenue LOOP
        v_rank := v_rank + 1;

        -- Tomada de decisão: classificar desempenho
        IF reg.revenue >= 300 THEN
            v_performance := 'Alto';
            v_high        := v_high + 1;
        ELSIF reg.revenue >= 150 THEN
            v_performance := 'Médio';
            v_mid         := v_mid + 1;
        ELSE
            v_performance := 'Baixo';
            v_low         := v_low + 1;
        END IF;

        DBMS_OUTPUT.PUT_LINE(RPAD(v_rank,6)||RPAD(reg.UF,5)||RPAD(reg.state,22)||
            RPAD(reg.qty,12)||
            RPAD('R$ '||TO_CHAR(reg.revenue,'FM99990.00'),16)||v_performance);

        v_total := v_total + reg.revenue;
    END LOOP;

    -- Resumo
    DBMS_OUTPUT.PUT_LINE(RPAD('-',80,'-'));
    DBMS_OUTPUT.PUT_LINE('Receita total: R$ '||TO_CHAR(v_total,'FM99990.00'));
    DBMS_OUTPUT.PUT_LINE('Estados de alto desempenho:   '||v_high);
    DBMS_OUTPUT.PUT_LINE('Estados de médio desempenho: '||v_mid);
    DBMS_OUTPUT.PUT_LINE('Estados de baixo desempenho:    '||v_low);
END;
