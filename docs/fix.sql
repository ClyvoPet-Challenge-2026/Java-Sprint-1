-- =====================================================================
-- Relatório LAG / LEAD: valor anterior, atual e próximo
-- =====================================================================
DECLARE
BEGIN
    DBMS_OUTPUT.PUT_LINE('=====================================================');
    DBMS_OUTPUT.PUT_LINE('  LAG / LEAD - VALOR ANTERIOR / ATUAL / PRÓXIMO      ');
    DBMS_OUTPUT.PUT_LINE('=====================================================');

    -- Assinaturas em ordem cronológica
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Assinaturas em ordem cronológica ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Pet',12)||RPAD('Plano',12)||
        RPAD('Vlr.Anterior',14)||RPAD('Vlr.Atual',14)||RPAD('Vlr.Próximo',14)||'Data');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',80,'-'));
    FOR r IN (
        SELECT p.NAME AS pet,
               pl.NAME AS plan,
               s.START_DATE,
               s.CONTRACTED_VALUE AS curr_value,
               LAG(s.CONTRACTED_VALUE)  OVER (ORDER BY s.START_DATE, s.ID) AS prev_value,
               LEAD(s.CONTRACTED_VALUE) OVER (ORDER BY s.START_DATE, s.ID) AS next_value
        FROM TB_CAD_SUBSCRIPTION s
        JOIN TB_CAD_PET p ON p.ID = s.PET_ID
        JOIN TB_CAD_PLAN pl ON pl.ID = s.PLAN_ID
        ORDER BY s.START_DATE, s.ID
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(
            RPAD(r.pet,12)||RPAD(r.plan,12)||
            RPAD(NVL('R$ '||TO_CHAR(r.prev_value,'FM990.00'),'---'),14)||
            RPAD('R$ '||TO_CHAR(r.curr_value,'FM990.00'),14)||
            RPAD(NVL('R$ '||TO_CHAR(r.next_value,'FM990.00'),'---'),14)||
            TO_CHAR(r.start_date,'DD/MM/YYYY'));
    END LOOP;

    -- Planos em ordem de valor
    DBMS_OUTPUT.PUT_LINE('');
    DBMS_OUTPUT.PUT_LINE('--- Planos em ordem de valor ---');
    DBMS_OUTPUT.PUT_LINE(RPAD('Plano Ant',14)||RPAD('R$ Ant',12)||
        RPAD('Plano Atual',14)||RPAD('R$ Atual',12)||
        RPAD('Prox Plano',14)||'R$ Prox');
    DBMS_OUTPUT.PUT_LINE(RPAD('-',78,'-'));
    FOR r IN (
        SELECT NAME AS curr_plan,
               MONTHLY_VALUE AS curr_value,
               LAG(NAME)          OVER (ORDER BY MONTHLY_VALUE) AS prev_plan,
               LAG(MONTHLY_VALUE) OVER (ORDER BY MONTHLY_VALUE) AS prev_value,
               LEAD(NAME)          OVER (ORDER BY MONTHLY_VALUE) AS next_plan,
               LEAD(MONTHLY_VALUE) OVER (ORDER BY MONTHLY_VALUE) AS next_value
        FROM TB_CAD_PLAN
        ORDER BY MONTHLY_VALUE
    ) LOOP
        DBMS_OUTPUT.PUT_LINE(
            RPAD(NVL(r.prev_plan,'---'),14)||
            RPAD(NVL(TO_CHAR(r.prev_value,'FM990.00'),'---'),12)||
            RPAD(r.curr_plan,14)||
            RPAD(TO_CHAR(r.curr_value,'FM990.00'),12)||
            RPAD(NVL(r.next_plan,'---'),14)||
            NVL(TO_CHAR(r.next_value,'FM990.00'),'---'));
    END LOOP;
END;
