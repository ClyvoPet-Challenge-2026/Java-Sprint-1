-- =====================================================================
-- Tabelas de domínio (Lookup)
-- =====================================================================

CREATE TABLE TB_CAD_SPECIES (
    ID         NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME       VARCHAR2(50)  NOT NULL UNIQUE,
    CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE TB_CAD_BREED (
    ID         NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    SPECIES_ID NUMBER(19) NOT NULL,
    NAME       VARCHAR2(100) NOT NULL,
    CONSTRAINT FK_BREED_SPECIES    FOREIGN KEY (SPECIES_ID) REFERENCES TB_CAD_SPECIES(ID),
    CONSTRAINT UK_BREED_SPECIES_NM UNIQUE (SPECIES_ID, NAME)
);

CREATE TABLE TB_CAD_STATE (
    ID   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    UF   VARCHAR2(2)      NOT NULL UNIQUE,
    NAME VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE TB_CAD_CITY (
    ID       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    STATE_ID NUMBER(19) NOT NULL,
    NAME     VARCHAR2(100) NOT NULL,
    CONSTRAINT FK_CITY_STATE    FOREIGN KEY (STATE_ID) REFERENCES TB_CAD_STATE(ID),
    CONSTRAINT UK_CITY_STATE_NM UNIQUE (STATE_ID, NAME)
);

CREATE TABLE TB_CAD_PAYMENT_METHOD (
    ID   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(50) NOT NULL UNIQUE
);

CREATE TABLE TB_CAD_SUB_STATUS (
    ID   NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME VARCHAR2(50) NOT NULL UNIQUE
);


CREATE TABLE TB_CAD_OWNER (
    ID            NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    CITY_ID       NUMBER(19)    NOT NULL,
    NAME          VARCHAR2(150) NOT NULL,
    CPF           VARCHAR2(14)  NOT NULL UNIQUE,
    EMAIL         VARCHAR2(150) NOT NULL UNIQUE,
    PASSWORD_HASH VARCHAR2(255) NOT NULL,
    ROLE_NAME     VARCHAR2(20)  DEFAULT 'OWNER' NOT NULL,
    ENABLED       CHAR(1)       DEFAULT 'Y' NOT NULL,
    PHONE         VARCHAR2(20)  NOT NULL,
    CREATED_AT    TIMESTAMP DEFAULT SYSTIMESTAMP,
    CONSTRAINT FK_OWNER_CITY     FOREIGN KEY (CITY_ID) REFERENCES TB_CAD_CITY(ID),
    CONSTRAINT CK_OWNER_ROLE    CHECK (ROLE_NAME IN ('ADMIN','OWNER')),
    CONSTRAINT CK_OWNER_ENABLED CHECK (ENABLED IN ('Y','N'))
);

CREATE TABLE TB_CAD_PLAN (
    ID            NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME          VARCHAR2(50) NOT NULL UNIQUE,
    MONTHLY_VALUE NUMBER(10,2) NOT NULL,
    CONSTRAINT CK_PLAN_VALUE CHECK (MONTHLY_VALUE > 0)
);

CREATE TABLE TB_CAD_PET (
    ID         NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    OWNER_ID   NUMBER(19)    NOT NULL,
    SPECIES_ID NUMBER(19)    NOT NULL,
    BREED_ID   NUMBER(19),
    NAME       VARCHAR2(100) NOT NULL,
    BIRTH_DATE DATE          NOT NULL,
    SEX        VARCHAR2(10)  CHECK (SEX IN ('MALE','FEMALE')),
    CONSTRAINT FK_PET_OWNER   FOREIGN KEY (OWNER_ID)   REFERENCES TB_CAD_OWNER(ID),
    CONSTRAINT FK_PET_SPECIES FOREIGN KEY (SPECIES_ID) REFERENCES TB_CAD_SPECIES(ID),
    CONSTRAINT FK_PET_BREED   FOREIGN KEY (BREED_ID)   REFERENCES TB_CAD_BREED(ID)
);

CREATE TABLE TB_CAD_SUBSCRIPTION (
    ID                 NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PET_ID             NUMBER(19)   NOT NULL,
    PLAN_ID            NUMBER(19)   NOT NULL,
    STATUS_ID          NUMBER(19)   NOT NULL,
    PAYMENT_METHOD_ID  NUMBER(19)   NOT NULL,
    START_DATE         DATE DEFAULT SYSDATE,
    CONTRACTED_VALUE   NUMBER(10,2) NOT NULL,
    CONSTRAINT FK_SUB_PET     FOREIGN KEY (PET_ID)            REFERENCES TB_CAD_PET(ID),
    CONSTRAINT FK_SUB_PLAN    FOREIGN KEY (PLAN_ID)           REFERENCES TB_CAD_PLAN(ID),
    CONSTRAINT FK_SUB_STATUS  FOREIGN KEY (STATUS_ID)         REFERENCES TB_CAD_SUB_STATUS(ID),
    CONSTRAINT FK_SUB_PAYMENT FOREIGN KEY (PAYMENT_METHOD_ID) REFERENCES TB_CAD_PAYMENT_METHOD(ID),
    CONSTRAINT CK_SUB_VALUE   CHECK (CONTRACTED_VALUE > 0)
);

CREATE TABLE TB_CAD_CLINIC (
    ID      NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    NAME    VARCHAR2(150) NOT NULL,
    CNPJ    VARCHAR2(18)  NOT NULL UNIQUE,
    CITY_ID NUMBER(19)    NOT NULL,
    PHONE   VARCHAR2(20),
    CONSTRAINT FK_CLINIC_CITY FOREIGN KEY (CITY_ID) REFERENCES TB_CAD_CITY(ID)
);

-- =====================================================================
-- Tabelas de saúde e log
-- =====================================================================

CREATE TABLE TB_HEA_CLINICAL_EVENT (
    ID         NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PET_ID     NUMBER(19)   NOT NULL,
    CLINIC_ID  NUMBER(19)   NOT NULL,
    EVENT_TYPE VARCHAR2(20) NOT NULL,
    EVENT_DATE TIMESTAMP    NOT NULL,
    STATUS     VARCHAR2(20) NOT NULL,
    CONSTRAINT FK_EVENT_PET    FOREIGN KEY (PET_ID)    REFERENCES TB_CAD_PET(ID),
    CONSTRAINT FK_EVENT_CLINIC FOREIGN KEY (CLINIC_ID) REFERENCES TB_CAD_CLINIC(ID),
    CONSTRAINT CK_EVENT_TYPE   CHECK (EVENT_TYPE IN ('CONSULTATION','VACCINATION','SURGERY','FOLLOW_UP','EXAM')),
    CONSTRAINT CK_EVENT_STATUS CHECK (STATUS IN ('SCHEDULED','COMPLETED','CANCELED'))
);

CREATE TABLE TB_HEA_REMINDER (
    ID       NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PET_ID   NUMBER(19)    NOT NULL,
    TITLE    VARCHAR2(150) NOT NULL,
    DUE_DATE DATE          NOT NULL,
    STATUS   VARCHAR2(20)  DEFAULT 'PENDING',
    CONSTRAINT FK_REMINDER_PET    FOREIGN KEY (PET_ID) REFERENCES TB_CAD_PET(ID),
    CONSTRAINT CK_REMINDER_STATUS CHECK (STATUS IN ('PENDING','COMPLETED','CANCELED'))
);

CREATE TABLE TB_HEA_ERROR_LOG (
    ID              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PROCEDURE_NAME  VARCHAR2(100),
    USER_NAME       VARCHAR2(100),
    OCCURRENCE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP,
    ERROR_CODE      VARCHAR2(20),
    ERROR_MESSAGE   VARCHAR2(2000)
);

-- Tabela de auditoria - alimentada pelo trigger TRG_SUBSCRIPTION_AUDIT
CREATE TABLE TB_HEA_AUDIT_LOG (
    ID              NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    TABLE_NAME      VARCHAR2(30)  NOT NULL,
    OPERATION       VARCHAR2(10)  NOT NULL,
    USER_NAME       VARCHAR2(100),
    OCCURRENCE_DATE TIMESTAMP DEFAULT SYSTIMESTAMP,
    ROW_PK          NUMBER(19),
    OLD_VALUES      VARCHAR2(4000),
    NEW_VALUES      VARCHAR2(4000),
    CONSTRAINT CK_AUDIT_OP CHECK (OPERATION IN ('INSERT','UPDATE','DELETE'))
);


