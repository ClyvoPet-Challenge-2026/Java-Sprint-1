               'SP_INSERT_SPECIES','SP_INSERT_BREED','SP_INSERT_STATE','SP_INSERT_CITY',
               'SP_INSERT_PAYMENT_METHOD','SP_INSERT_STATUS','SP_INSERT_PLAN','SP_INSERT_OWNER',
