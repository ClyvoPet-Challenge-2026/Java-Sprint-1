SELECT FN_SUBSCRIPTION_TO_JSON(999999) AS json_erro_id FROM DUAL;
SELECT FN_SUBSCRIPTION_TO_JSON(NULL)   AS json_erro_nulo FROM DUAL;

-- Função 2: valores calculados e os dois casos de erro
SELECT p.NAME  AS plano,
       pm.NAME AS metodo,
       p.MONTHLY_VALUE                          AS valor_tabela,
       FN_CALCULATE_CONTRACT_VALUE(p.ID, pm.ID) AS valor_calculado
  FROM TB_CAD_PLAN p
  CROSS JOIN TB_CAD_PAYMENT_METHOD pm
 WHERE p.NAME = 'Premium'
   AND pm.NAME IN ('Card','Pix','Auto Debit')
 ORDER BY pm.NAME;

DECLARE
    v NUMBER;
BEGIN
    BEGIN
        v := FN_CALCULATE_CONTRACT_VALUE(NULL, 1);
    EXCEPTION
        WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('Erro capturado: ' || SQLERRM);
    END;
    BEGIN
        v := FN_CALCULATE_CONTRACT_VALUE(999, 999);
    EXCEPTION
        WHEN OTHERS THEN DBMS_OUTPUT.PUT_LINE('Erro capturado: ' || SQLERRM);
    END;
END;
/

