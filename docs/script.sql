BEGIN
    FOR t IN (
        SELECT table_name FROM user_tables
        WHERE table_name IN (
            'TB_HEA_AUDIT_LOG','TB_HEA_ERROR_LOG','TB_HEA_REMINDER','TB_HEA_CLINICAL_EVENT',
            'TB_CAD_USER','TB_CAD_SUBSCRIPTION','TB_CAD_SUB_STATUS','TB_CAD_PAYMENT_METHOD',
