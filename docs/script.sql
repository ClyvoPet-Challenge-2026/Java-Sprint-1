               'FN_SUBSCRIPTION_TO_JSON','FN_CALCULATE_CONTRACT_VALUE','TRG_SUBSCRIPTION_AUDIT'
           )
    ) LOOP
        EXECUTE IMMEDIATE 'DROP ' || o.object_type || ' ' || o.object_name;
    END LOOP;
END;
